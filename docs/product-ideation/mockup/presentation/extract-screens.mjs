// Reads ../index.html (the mockup) in a headless browser and copies out the markup the
// presentation needs: the mockup's stylesheet, its role and screen names, and each
// screen exactly as the mockup renders it at a given guided step. The mockup file is
// only read. Output: screens.generated.js
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { HERE, MOCKUP, fileUrl, launch, loadStoryboard } from "./tools.mjs";

export async function extract() {
  const board = loadStoryboard();
  const needs = new Map();
  const need = (step, role, page) => needs.set(`${step}|${role}|${page}`, { step, role, page });
  for (const beat of board.beats) {
    if (beat.kind === "screen") for (const step of beat.steps) need(step, beat.role, beat.page);
  }
  const gridBeats = board.beats.filter((b) => b.kind === "grid");

  const browser = await launch();
  try {
    const page = await browser.newPage();
    await page.setViewport({ width: 1600, height: 1000, deviceScaleFactor: 1 });
    const errors = [];
    page.on("pageerror", (e) => errors.push(String(e)));
    await page.goto(fileUrl(MOCKUP), { waitUntil: "load" });

    const data = await page.evaluate(
      (scenario, needList, grids) => {
        /* global stories, storyId:writable, role:writable, page:writable, persona:writable, mode:writable,
           auditOpened:writable, jump, render, roleNames, pages, limits, SIMULATED_DEMO */
        const story = stories.find((s) => s.id === scenario);
        if (!story) throw new Error("Scenario not found in the mockup: " + scenario);
        const show = (step, r, p) => {
          storyId = scenario;
          jump(step - 1);
          role = r; page = p; persona = "payer"; mode = "screens"; auditOpened = false;
          render(false);
          const guided = story.steps[step - 1];
          return {
            html: document.getElementById("screen").innerHTML,
            guided: guided.role === r && guided.page === p,
          };
        };
        const sidebar = (r) => {
          role = r; page = pages[r][0][0]; mode = "map"; render(false); // map mode: no nav item is current
          const copy = document.querySelector(".sidebar").cloneNode(true);
          copy.querySelectorAll("#role option").forEach((o) => o.toggleAttribute("selected", o.value === r));
          copy.querySelectorAll("#person option").forEach((o) => o.toggleAttribute("selected", o.value === "payer"));
          return copy.innerHTML;
        };
        const screens = {};
        for (const n of needList) screens[`${n.step}|${n.role}|${n.page}`] = show(n.step, n.role, n.page);
        for (const g of grids) for (const [p] of pages[g.role]) screens[`${g.step}|${g.role}|${p}`] = show(g.step, g.role, p);
        const sidebars = {};
        for (const r of Object.keys(roleNames)) sidebars[r] = sidebar(r);
        return {
          css: document.querySelector("style").textContent,
          brand: document.querySelector(".masthead .brand").innerHTML,
          brandSubtitle: document.querySelector(".masthead .brand span").textContent,
          banner: document.querySelector(".demo-banner").innerHTML,
          footer: document.querySelector(".footer p").textContent,
          roleNames, pages, limits,
          demo: SIMULATED_DEMO,
          scenario: { id: story.id, name: story.name, steps: story.steps.map((s) => ({ role: s.role, page: s.page, title: s.title, action: s.action })) },
          sidebars, screens,
        };
      },
      board.scenario,
      [...needs.values()],
      gridBeats.map((b) => ({ role: b.role, step: b.step })),
    );
    if (errors.length) throw new Error("The mockup raised script errors: " + errors.join("; "));

    data.source = {
      file: "../index.html",
      sha256: createHash("sha256").update(readFileSync(MOCKUP)).digest("hex"),
    };
    const out =
      "// Generated by extract-screens.mjs from ../index.html. Do not edit; run `npm run extract`.\n" +
      "window.MOCK = " + JSON.stringify(data, null, 1) + ";\n";
    writeFileSync(join(HERE, "screens.generated.js"), out);
    return { screens: Object.keys(data.screens).length, bytes: out.length };
  } finally {
    await browser.close();
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await extract();
  console.log(`Extracted ${result.screens} screens from the mockup (${(result.bytes / 1024).toFixed(0)} KB) -> screens.generated.js`);
}
